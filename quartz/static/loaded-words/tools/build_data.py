def score_synset(syn, spec):
    text = " " + syn.definition().lower() + " "
    score = 0
    for pattern, weight in spec["markers"]:
        if re.search(pattern, text):
            score += weight
    score += spec["lexfiles"].get(syn.lexfile(), 0)
    return score


def choose_synset(word, spec):
    best = None
    best_score = 0
    synsets = wn.synsets(word, lang="en")
    for syn in synsets:
        score = score_synset(syn, spec)
        if score > best_score:
            best = syn
            best_score = score
    if best_score == 0:
        # Fall back to the first sense for technical-only words. The curated
        # context list is the editorial check; WordNet supplies the wording.
        return synsets[0] if synsets else None
    return best


def clean(text):
    text = re.sub(r"\s+", " ", text).strip()
    return text.replace('"', '\\"')


def example_for(syn):
    for ex in syn.examples():
        ex = re.sub(r"\s+", " ", ex).strip()
        if 20 <= len(ex) <= 110:
            return ex
    return ""


def subfield(syn):
    d = syn.definition().lower()
    for key, label in [
        ("biology", "biology"), ("botany", "biology"), ("zoology", "biology"),
        ("medicine", "medicine"), ("anatomy", "medicine"),
        ("chemistry", "chemistry"), ("physics", "physics"),
        ("geology", "geology"), ("astronomy", "astronomy"),
    ]:
        if key in d:
            return label
    lf = syn.lexfile()
    return {
        "noun.plant": "biology", "noun.animal": "biology",
        "noun.body": "medicine", "noun.substance": "chemistry",
        "noun.phenomenon": "physics", "noun.object": "geology",
    }.get(lf, "")


def sense_obj(ctx, syn, manual=None):
    if manual:
        return {"c": ctx, "d": manual, "src": "LW"}
    obj = {"c": ctx, "d": clean(syn.definition()), "src": "OEWN"}
    ex = example_for(syn)
    if ex:
        obj["e"] = clean(ex)
    if ctx == "science":
        sub = subfield(syn)
        if sub:
            obj["s"] = sub
    return obj


GENERAL_BAD = re.compile(r"\b(United States|American|English|British|Greek|Roman|Christian|President|actor|actress|city|county|state|river|king|queen|saint|god|goddess)\b", re.I)


def general_sense(word, domain_synsets):
    domain_ids = {s.id for s in domain_synsets if s is not None}
    candidates = wn.synsets(word, lang="en")
    for syn in candidates:
        if syn.id in domain_ids:
            continue
        lemmas = syn.lemmas()
        # Skip proper-noun synsets: a common word's general sense should be
        # spelled lowercase, not "Bush" or "Tree".
        if not any(l == word for l in lemmas):
            continue
        if GENERAL_BAD.search(syn.definition()):
            continue
        return sense_obj("general", syn)
    return None


def build():
    wn.config.allow_multithreading = True
    try:
        wn.add(LEXICON)
    except Exception:
        pass

    entries = {}

    def entry(word):
        if word not in entries:
            entries[word] = {
                "w": word,
                "f": round(zipf_frequency(word, "en"), 2),
                "senses": [],
                "_ids": set(),
            }
        return entries[word]

    for ctx, spec in SPECS.items():
        found = 0
        for word in spec["words"]:
            e = entry(word)
            if any(s["c"] == ctx for s in e["senses"]):
                continue
            manual = OVERRIDES.get((ctx, word))
            if manual:
                e["senses"].append(sense_obj(ctx, None, manual))
                found += 1
                continue
            syn = choose_synset(word, spec)
            if syn is None:
                continue
            e["senses"].append(sense_obj(ctx, syn))
            e["_ids"].add(syn.id)
            found += 1
        print(f"{ctx}: {found} / {len(spec['words'])} candidate words")

    # Risqué is hand-written where possible. Otherwise use a WordNet gloss that
    # clearly describes a sexual sense.
    risque_spec = {
        "markers": [
            (r"\bsex\b", 8), (r"\bsexual\b", 8), (r"\bintercourse\b", 8),
            (r"\bpenis\b", 8), (r"\bvagina\b", 8), (r"\bgenital", 7),
            (r"\berotic\b", 7), (r"\borgasm\b", 7), (r"\bsemen\b", 7),
            (r"\bbreast", 6), (r"\bbuttock", 6), (r"\banus\b", 7),
            (r"\bcopulat", 7), (r"\bmasturbat", 7),
        ],
        "lexfiles": {},
    }
    rfound = 0
    for word in RISQUE_WORDS:
        manual = RISQUE_MANUAL.get(word)
        if manual:
            e = entry(word)
            if not any(s["c"] == "risque" for s in e["senses"]):
                e["senses"].append(sense_obj("risque", None, manual))
                rfound += 1
            continue
        syn = choose_synset(word, risque_spec)
        if syn is None:
            continue
        e = entry(word)
        if not any(s["c"] == "risque" for s in e["senses"]):
            e["senses"].append(sense_obj("risque", syn))
            e["_ids"].add(syn.id)
            rfound += 1
    print(f"risque: {rfound} / {len(RISQUE_WORDS)} candidate words")

    # Add a general sense where WordNet offers one that is not already used.
    for word, e in entries.items():
        if any(s["c"] == "general" for s in e["senses"]):
            continue
        if word in SKIP_GENERAL:
            continue
        manual = GENERAL_OVERRIDES.get(word)
        if manual:
            e["senses"].insert(0, sense_obj("general", None, manual))
            continue
        domain = []
        for syn in wn.synsets(word, lang="en"):
            if syn.id in e["_ids"]:
                domain.append(syn)
        g = general_sense(word, domain)
        if g:
            e["senses"].insert(0, g)

    # Sort senses in display order, and drop duplicate definitions.
    order = {c: i for i, c in enumerate(["general", "risque", "math", "science", "computing", "military", "food", "music"])}
    for e in entries.values():
        seen = set()
        clean_senses = []
        for s in sorted(e["senses"], key=lambda x: order.get(x["c"], 99)):
            key = (s["c"], s["d"])
            if key in seen:
                continue
            seen.add(key)
            clean_senses.append(s)
        e["senses"] = clean_senses

    data = sorted(entries.values(), key=lambda e: (-len({s["c"] for s in e["senses"]}), -e["f"], e["w"]))
    data = [e for e in data if len(e["senses"]) >= 1]
    for e in data:
        e.pop("_ids", None)

    # Write a readable JS file. The browser loads it as a classic script.
    lines = [
        "// Generated by tools/build_data.py. Do not edit by hand.",
        "// Glosses: Open English WordNet 2024 (CC BY 4.0) unless src is \"LW\".",
        "window.LOADED_WORDS = [",
    ]
    for e in data:
        senses = []
        for s in e["senses"]:
            parts = [f'c:"{s["c"]}"', f'd:"{s["d"]}"']
            if s.get("s"):
                parts.append(f's:"{s["s"]}"')
            if s.get("e"):
                parts.append(f'e:"{s["e"]}"')
            parts.append(f'src:"{s["src"]}"')
            senses.append("{" + ",".join(parts) + "}")
        lines.append(f'  {{w:"{e["w"]}",f:{e["f"]},senses:[' + ",".join(senses) + "]},")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    counts = {c: 0 for c in order}
    loaded = 0
    for e in data:
        contexts = {s["c"] for s in e["senses"]}
        if len(contexts) >= 2:
            loaded += 1
        for c in contexts:
            counts[c] += 1
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")
    print(f"words: {len(data)}, loaded (2+ contexts): {loaded}")
    print("context counts:", json.dumps(counts, indent=2))
    print("top contexts:", sorted(counts.items(), key=lambda kv: -kv[1])[:5])


if __name__ == "__main__":
    build()
